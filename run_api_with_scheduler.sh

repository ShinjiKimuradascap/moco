#!/bin/bash

# Start moco UI with scheduler enabled
# This will run on port 8000 and the scheduler will execute scheduled tasks

cd "$(dirname "$0")"
echo "Starting moco UI with scheduler..."
echo "API will be available at http://localhost:8000"
echo ""
echo "Press Ctrl+C to stop"

# Set working directory and start API
export MOCO_WORKING_DIRECTORY="$(pwd)"

# Run the API directly (not using moco ui command)
python -m moco.ui.api
