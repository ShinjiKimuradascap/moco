#!/usr/bin/env python3
"""
スケジュールタスクの直接実行テスト
"""
import asyncio
import sys
from pathlib import Path

# Add src to path
sys.path.insert(0, str(Path(__file__).parent / "src"))

from moco.storage.scheduled_task_store import ScheduledTaskStore
from moco.tools.mobile import NotifyMobileTool

async def main():
    print("=" * 60)
    print("Testing Scheduled Task Execution")
    print("=" * 60)
    
    # Get enabled tasks
    store = ScheduledTaskStore()
    tasks = store.get_enabled_tasks()
    print(f"Found {len(tasks)} enabled tasks")
    for t in tasks:
        print(f"  - {t['id']}: {t['description'][:40]} | {t['cron']}")
    
    # Get due tasks
    due_tasks = store.get_due_tasks()
    print(f"Found {len(due_tasks)} due tasks")
    
    if due_tasks:
        print("\nProcessing due tasks...")
        notify_tool = NotifyMobileTool()
        
        for task in due_tasks:
            task_id = task['id']
            description = task['description']
            
            print(f"Processing task: {task_id}")
            
            # Send notification
            notification = f"""
📅 スケジュールタスク実行テスト

タスク: {description}
ID: {task_id}

注意: このメッセージはスケジュールタスクのテスト通知です。
実際のタスク実行はスケジューラーAPI経由で行われます。
            """.strip()
            
            try:
                result = await notify_tool.execute(notification)
                print(f"✅ Notification sent: {result[:100]}...")
                store.complete_task(task_id)
                print(f"Task {task_id} marked as completed")
            except Exception as e:
                print(f"❌ Error: {e}")
                store.complete_task(task_id)
    else:
        print("No due tasks to process")
    
    print("\n" + "=" * 60)

if __name__ == "__main__":
    try:
        asyncio.run(main())
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
